const C: Record<string, { bg: string; fg: string; label: string }> = {
  pass: { bg: "#e7f0e4", fg: "#2e5d24", label: "PASS" },
  warn: { bg: "#fdeee4", fg: "#a04312", label: "WARN" },
  fail: { bg: "#fbe5e8", fg: "#a01c30", label: "FAIL" },
  info: { bg: "#e9eef6", fg: "#2b4a76", label: "INFO" },
  skip: { bg: "#eeeeee", fg: "#666666", label: "SKIP" },
};

const esc = (s: string) =>
  s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");

function chip(status: string): string {
  const c = C[status] ?? C.info;
  return `<span class="chip" style="background:${c.bg};color:${c.fg}">${c.label}</span>`;
}

