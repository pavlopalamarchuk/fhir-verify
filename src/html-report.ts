export function renderRunHtml(report: RunReport): string {
  const flat = report.packs.flatMap((p) => p.results);
  const count = (s: string) => flat.filter((r) => r.status === s).length;
  const tiles = ["pass", "warn", "fail", "info", "skip"]
    .map(
      (s) =>
        `<div class="tile" style="border-top:3px solid ${C[s].fg}"><b>${count(s)}</b><span>${s}</span></div>`,
    )
    .join("");
  const packs = report.packs
    .map(
      (p) => `
    <h2>${esc(p.name)}</h2>
    <div class="card">${p.results
      .map(
        (r: CheckResult) => `
      <div class="row">
        <div>${chip(r.status)}</div>
        <div>
          <div class="t">${esc(r.title)}</div>
          <div class="d">${esc(r.details)}</div>
          ${r.references?.length ? `<div class="refs">Refs: ${r.references.map(esc).join(" · ")}</div>` : ""}
          ${
            r.evidence
              ? `<details><summary>evidence</summary><pre>${esc(JSON.stringify(r.evidence, null, 2))}</pre></details>`
              : ""
          }
        </div>
      </div>`,
      )
      .join("")}</div>`,
    )
    .join("");
  return `<!doctype html><html><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">
<title>fhir-verify — ${esc(report.serverUrl)}</title><style>${BASE_CSS}</style></head><body><div class="wrap">
  <h1>fhir-verify report</h1>
  <div class="meta">Server: <b>${esc(report.serverUrl)}</b></div>
  <div class="meta">Run: ${esc(report.startedAt)} → ${esc(report.finishedAt)} · ${esc(report.tool)} v${esc(report.version)}</div>
  <div class="totals">${tiles}</div>
  ${packs}
  <div class="foot">Generated by fhir-verify — the operational basics every production FHIR integration depends on. Synthetic data only.</div>
</div></body></html>`;
}

/** Build a cross-server behavior matrix from multiple run reports. */
export function renderMatrixHtml(reports: RunReport[]): string {
  const servers = reports.map((r) => {
    const labeled = (r as RunReport & { label?: string }).label;
    if (labeled) return labeled;
    try {
      const u = new URL(r.serverUrl);
      return u.hostname.replace(/^www\./, "");
    } catch {
      return r.serverUrl;
    }
  });
  // union of check ids in first-seen order
  const ids: string[] = [];
  const titleById = new Map<string, string>();
  for (const rep of reports)
    for (const p of rep.packs)
      for (const c of p.results) {
        if (!titleById.has(c.id)) {
          ids.push(c.id);
          titleById.set(c.id, c.title);
        }
      }
  const cell = (rep: RunReport, id: string) => {
    for (const p of rep.packs) for (const c of p.results) if (c.id === id) return c;
    return undefined;
  };
  const rows = ids
    .map((id) => {
      const tds = reports
        .map((rep) => {
          const c = cell(rep, id);
          return `<td title="${c ? esc(c.details) : "not run"}">${c ? chip(c.status) : "—"}</td>`;
        })
        .join("");
      return `<tr><td class="first">${esc(titleById.get(id) ?? id)}<div class="refs">${esc(id)}</div></td>${tds}</tr>`;
    })
    .join("");
  return `<!doctype html><html><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">
<title>fhir-verify — behavior matrix</title><style>${BASE_CSS}</style></head><body><div class="wrap">
  <h1>FHIR server behavior matrix</h1>
  <div class="meta">${reports.length} servers · generated by fhir-verify (hover a cell for details)</div>
  <div style="overflow-x:auto;margin-top:16px"><table>
    <thead><tr><th class="first">Check</th>${servers.map((s) => `<th>${esc(s)}</th>`).join("")}</tr></thead>
    <tbody>${rows}</tbody>
  </table></div>
  <div class="foot">Same probes, same synthetic data, one command per server. Certification proves a server can; operations is where it does.</div>
</div></body></html>`;
}
